namespace Internal {
    // Маркер сгенерированного класса биндингов. По нему генератор находит границу вьюхи:
    // в объект с собственными биндингами он не спускается, а кладёт ссылку на его компонент.
    // Это же обнуляет глубину вложенности сериализации, которой у Unity всего семь уровней.
    public interface IObjectBindings {
        // Слепок иерархии на момент генерации: имена и типы компонентов в порядке обхода.
        // Нужен, чтобы поймать расхождение между сгенерированным классом и живой иерархией.
        string StructureHash { get; }
    }
}
